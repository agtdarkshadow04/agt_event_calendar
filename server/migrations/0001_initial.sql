-- Initial schema for the self-hosted AGT Event Calendar.
-- The schema version is recorded in PRAGMA user_version by the migration runner.

CREATE TABLE images (
  id TEXT PRIMARY KEY,                 -- UUIDv4, also the stored file's base name
  file_name TEXT NOT NULL UNIQUE,      -- server-generated: <id>.<ext>
  mime_type TEXT NOT NULL CHECK (mime_type IN ('image/png', 'image/jpeg', 'image/webp', 'image/gif')),
  size_bytes INTEGER NOT NULL CHECK (size_bytes > 0),
  sha256 TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE events (
  id TEXT PRIMARY KEY,                 -- RFC 9562 UUIDv4, generated by the server
  legacy_id TEXT UNIQUE CHECK (legacy_id IS NULL OR (length(legacy_id) = 4 AND legacy_id NOT GLOB '*[^0-9A-F]*')),
  name TEXT NOT NULL,
  start_utc TEXT NOT NULL,
  end_utc TEXT,
  civilization TEXT,
  type TEXT NOT NULL,
  description_md TEXT,
  cover_image_id TEXT REFERENCES images(id) ON DELETE SET NULL,
  galaxy TEXT NOT NULL,
  region TEXT NOT NULL,
  system TEXT NOT NULL,
  planet TEXT,
  portal_code TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('published', 'unpublished', 'pending', 'rejected')),
  submitter_agt_username TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX events_status_start ON events (status, start_utc);

CREATE TABLE event_links (
  event_id TEXT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  position INTEGER NOT NULL,
  url TEXT NOT NULL,
  PRIMARY KEY (event_id, position)
);

CREATE TABLE national_holidays (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  civilization TEXT NOT NULL,
  date TEXT NOT NULL,                  -- YYYY-MM-DD, first occurrence
  type TEXT NOT NULL,
  published INTEGER NOT NULL DEFAULT 1 CHECK (published IN (0, 1)),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE changelog (
  id TEXT PRIMARY KEY,
  date TEXT NOT NULL,                  -- YYYY-MM-DD
  changes TEXT NOT NULL,
  published INTEGER NOT NULL DEFAULT 1 CHECK (published IN (0, 1)),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- Dashboard-editable settings. Keys defined in config.yaml always win.
CREATE TABLE settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,                 -- JSON
  updated_at TEXT NOT NULL
);

-- The single admin account. Only a salted scrypt hash is stored.
CREATE TABLE admin (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  username TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- Admin sessions; only a SHA-256 of the session token is stored.
CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);

-- Server-generated secrets (e.g. the ALTCHA HMAC key when not set in config.yaml).
CREATE TABLE app_secrets (
  name TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- Used ALTCHA challenges, so each solution is accepted only once.
CREATE TABLE altcha_used (
  challenge_id TEXT PRIMARY KEY,
  expires_at INTEGER NOT NULL
);
